const MAP = new Map(TABLE)
const ORDERED = [...TABLE].sort((a, b) => b[0].length - a[0].length)
const escape = (value: string): string => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const PATTERN = new RegExp(ORDERED.map(([key]) => escape(key)).join('|'), 'g')

export function xsampaToIpa(input: string): string {
  if (!input) return ''
  return input.replace(PATTERN, (match) => MAP.get(match) ?? match)
}
